def build_options(text: str, correct: str, wrong: list[str]) -> tuple[list[str], int]:
    """گزینه‌ها و اندیس جواب درست؛ جای جواب درست از روی متن سوال (قطعی) تعیین می‌شود."""
    index = hashlib.sha256(text.encode("utf-8")).digest()[0] % (len(wrong) + 1)
    options = list(wrong)
    options.insert(index, correct)
    return options, index


