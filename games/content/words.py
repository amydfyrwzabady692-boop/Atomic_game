# چند کلمه‌ی دوحرفی/خیلی کوتاه برای بازی‌ها مناسب نیستند
MIN_LENGTH = 2
MAX_LENGTH = 12


def load_words() -> list[tuple[str, str]]:
    """لیست یکتای ``(کلمه، دسته)`` با کلمات نرمال‌شده."""
    seen: dict[str, str] = {}
    for category, block in _RAW.items():
        for raw in block.split():
            word = normalize_fa(raw, keep_spaces=False)
            if MIN_LENGTH <= len(word) <= MAX_LENGTH and word.isalpha() and word not in seen:
                seen[word] = category
    return list(seen.items())


def difficulty_of(word: str) -> int:
    return 1 if len(word) <= 4 else 2 if len(word) <= 6 else 3
